"""Evaluation metrics: deterministic checks on the match + G-Eval judges on the letter.

Deterministic (no LLM):
  - score_in_range   1.0 if `match.score` is inside the annotated `expected_score_range`
  - skills_recall    share of `must_match_skills` found in `match.matched_skills`
  - gaps_recall      share of `must_flag_gaps` found in `match.gaps[].skill`
  Matching is case/accent-insensitive and fuzzy; an annotation may list alternatives
  separated by "|" (e.g. "Cypress|tests e2e"). An empty annotation list scores 1.0.

G-Eval (local Qwen judge, scores normalised to 0-1):
  - letter_faithfulness  every claim in the letter is supported by the CV  (most important)
  - letter_relevance     letter addresses the offer's key requirements, right language, tone
  - gap_usefulness       gap advice is concrete and actionable
Evaluation steps are fixed (not generated by the judge) so results are comparable across runs.
"""

from __future__ import annotations

import re
import unicodedata
from difflib import SequenceMatcher

from deepeval.metrics import GEval
from deepeval.models import DeepEvalBaseLLM
from deepeval.test_case import LLMTestCase, SingleTurnParams

from jobmatch.schemas import CoverLetter, MatchResult

FUZZY_RATIO = 0.85

LANGUAGE_NAMES = {"fr": "French", "en": "English"}


# --------------------------------------------------------------------------- deterministic


def normalize(text: str) -> str:
    """casefold, strip accents, keep alphanumerics separated by single spaces."""
    text = unicodedata.normalize("NFKD", text.casefold())
    text = "".join(c for c in text if not unicodedata.combining(c))
    return " ".join(re.sub(r"[^a-z0-9+#]+", " ", text).split())


def fuzzy_contains(expected: str, candidates: list[str]) -> bool:
    """True if any `|`-separated alternative of `expected` matches one of `candidates`."""
    norm_candidates = [normalize(c) for c in candidates]
    for alt in (normalize(a) for a in expected.split("|")):
        if not alt:
            continue
        for cand in norm_candidates:
            if not cand:
                continue
            # whole-word containment either way ("PostgreSQL" ⊂ "PostgreSQL (Redshift)")
            if re.search(rf"(?<![a-z0-9]){re.escape(alt)}(?![a-z0-9])", cand):
                return True
            if re.search(rf"(?<![a-z0-9]){re.escape(cand)}(?![a-z0-9])", alt):
                return True
            if SequenceMatcher(None, alt, cand).ratio() >= FUZZY_RATIO:
                return True
    return False


def recall(expected: list[str], found: list[str]) -> tuple[float, list[str]]:
    """(recall, missing items). Empty expectation -> 1.0."""
    if not expected:
        return 1.0, []
    missing = [e for e in expected if not fuzzy_contains(e, found)]
    return 1 - len(missing) / len(expected), missing


def deterministic_metrics(case: dict, match: MatchResult) -> dict[str, dict]:
    lo, hi = case["expected_score_range"]
    skills, missing_skills = recall(case.get("must_match_skills", []), match.matched_skills)
    gaps, missing_gaps = recall(case.get("must_flag_gaps", []), [g.skill for g in match.gaps])
    return {
        "score_in_range": {
            "value": float(lo <= match.score <= hi),
            "reason": f"score {match.score}, expected [{lo}, {hi}]",
        },
        "skills_recall": {
            "value": skills,
            "reason": f"missing: {missing_skills}" if missing_skills else "all found",
        },
        "gaps_recall": {
            "value": gaps,
            "reason": f"missing: {missing_gaps}" if missing_gaps else "all flagged",
        },
    }


# --------------------------------------------------------------------------- G-Eval

FAITHFULNESS_STEPS = [
    "Read the candidate's CV ('input') carefully; it is the ONLY source of truth about the "
    "candidate.",
    "List every factual claim the cover letter ('actual output') makes about the candidate: "
    "employers, roles, durations / years of experience, technologies, figures, achievements, "
    "certifications, diplomas, languages, management responsibilities.",
    "For each claim, check whether the CV states or directly implies it. Rephrasing and "
    "reasonable summarising are fine; motivation statements and enthusiasm about the job are "
    "not factual claims and must be ignored.",
    "Penalise heavily any claim that is absent from or contradicted by the CV (invented "
    "skill, employer, number, certification, inflated seniority or duration).",
    "Give the maximum score only if every factual claim is supported; one clear "
    "hallucination should bring the score below 5, several below 3.",
]

RELEVANCE_STEPS = [
    "Identify the key requirements and missions of the job offer ('input').",
    "Check that the cover letter ('actual output') explicitly addresses the most important "
    "requirements, linking them to the candidate's experience rather than staying generic.",
    "Check that the letter is written in the language stated at the top of the input "
    "(expected letter language); a letter in another language must get a score of 2 or less.",
    "Check that the tone is professional, the structure is that of a cover letter "
    "(greeting, body, closing) and that it is reasonably concise.",
    "Do not judge whether the claims about the candidate are true (another metric does it).",
]

GAP_USEFULNESS_STEPS = [
    "The input contains the job offer, the candidate CV and the list of identified skill gaps; "
    "the actual output is the advice given for each gap.",
    "For each gap, check that the advice is concrete and actionable: a specific resource, "
    "project, certification, or a precise way to leverage existing CV experience or address "
    "the gap in an interview.",
    "Penalise generic advice ('se former', 'learn the skill', 'gain experience') and advice "
    "that ignores the candidate's actual background.",
    "Penalise advice that is unrealistic for the gap (e.g. advising years of study for a "
    "nice-to-have tool) or that is not related to the skill.",
    "If there are no gaps listed, give the maximum score.",
]


def build_geval_metrics(judge: DeepEvalBaseLLM) -> dict[str, GEval]:
    """Fresh metric instances (GEval stores its last score, so never share across cases)."""
    common = {"model": judge, "async_mode": True, "threshold": 0.5}
    io = [SingleTurnParams.INPUT, SingleTurnParams.ACTUAL_OUTPUT]
    return {
        "letter_faithfulness": GEval(
            name="Letter faithfulness",
            evaluation_steps=FAITHFULNESS_STEPS,
            evaluation_params=io,
            **common,
        ),
        "letter_relevance": GEval(
            name="Letter relevance",
            evaluation_steps=RELEVANCE_STEPS,
            evaluation_params=io,
            **common,
        ),
        "gap_usefulness": GEval(
            name="Gap analysis usefulness",
            evaluation_steps=GAP_USEFULNESS_STEPS,
            evaluation_params=io,
            **common,
        ),
    }


def letter_text(letter: CoverLetter) -> str:
    return f"Subject: {letter.subject}\n\n{letter.body}"


def geval_test_cases(case: dict, output: dict) -> dict[str, LLMTestCase]:
    """One LLMTestCase per G-Eval metric, built from the cached graph output."""
    letter = CoverLetter.model_validate(output["cover_letter"])
    match = MatchResult.model_validate(output["match"])
    offer_lang = output.get("offer", {}).get("language") or letter.language
    lang_name = LANGUAGE_NAMES.get(offer_lang, offer_lang)
    gaps = "\n".join(f"- {g.skill} ({g.level.value})" for g in match.gaps) or "(none)"
    advice = "\n".join(f"- {g.skill}: {g.advice}" for g in match.gaps) or "(no gaps)"
    return {
        "letter_faithfulness": LLMTestCase(
            input=case["cv_text"], actual_output=letter_text(letter)
        ),
        "letter_relevance": LLMTestCase(
            input=f"Expected letter language: {lang_name}\n\nJob offer:\n{case['offer_text']}",
            actual_output=letter_text(letter),
        ),
        "gap_usefulness": LLMTestCase(
            input=(
                f"Job offer:\n{case['offer_text']}\n\nCandidate CV:\n{case['cv_text']}\n\n"
                f"Identified gaps:\n{gaps}"
            ),
            actual_output=advice,
        ),
    }
